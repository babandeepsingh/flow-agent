//! Per-run configuration passed to every [`Runnable`](crate::Runnable).

use std::fmt;
use std::sync::Arc;
use std::time::Duration;

use serde::{Deserialize, Serialize};
use serde_json::{Map, Value};
use tokio_util::sync::CancellationToken;
use uuid::Uuid;

use crate::event::{CallbackHandler, Event, EventSink};

/// Default number of graph supersteps before [`Error::RecursionLimit`](crate::Error::RecursionLimit).
pub const DEFAULT_RECURSION_LIMIT: u32 = 25;

/// Default concurrency for `batch` and parallel steps.
pub const DEFAULT_MAX_CONCURRENCY: usize = 16;

/// Configuration for one run: identity, tags, limits, callbacks and cancellation.
///
/// Passed by reference through every call; cloning is cheap. Built with
/// chained setters:
///
/// ```
/// use flow_agent_core::RunConfig;
/// use serde_json::json;
/// use std::time::Duration;
///
/// let config = RunConfig::new()
///     .thread_id("user-42")
///     .tag("prod")
///     .metadata("tenant", json!("acme"))
///     .recursion_limit(50)
///     .timeout(Duration::from_secs(60));
/// assert_eq!(config.thread_id.as_deref(), Some("user-42"));
/// ```
///
/// Runtime-only handles (callbacks, cancellation, the internal event sink)
/// are skipped when serializing.
#[derive(Clone, Serialize, Deserialize)]
#[non_exhaustive]
pub struct RunConfig {
    /// Conversation/thread id. Required for checkpointing.
    #[serde(default)]
    pub thread_id: Option<String>,
    /// Resume or fork from this checkpoint instead of the latest.
    #[serde(default)]
    pub checkpoint_id: Option<String>,
    /// Id of this run (UUID v7). Generated by [`RunConfig::new`].
    #[serde(default = "Uuid::now_v7")]
    pub run_id: Uuid,
    /// Id of the run that started this one.
    #[serde(default)]
    pub parent_run_id: Option<Uuid>,
    /// Optional run name shown in traces.
    #[serde(default)]
    pub run_name: Option<String>,
    /// Tags for filtering traces.
    #[serde(default)]
    pub tags: Vec<String>,
    /// Arbitrary metadata.
    #[serde(default)]
    pub metadata: Map<String, Value>,
    /// Free-form runtime options that components may read.
    #[serde(default)]
    pub configurable: Map<String, Value>,
    /// Max graph supersteps.
    #[serde(default = "default_recursion_limit")]
    pub recursion_limit: u32,
    /// Max concurrent tasks for `batch` and parallel execution.
    #[serde(default = "default_max_concurrency")]
    pub max_concurrency: usize,
    /// Timeout for the whole run (enforced by graphs and `with_timeout`).
    #[serde(default)]
    pub timeout: Option<Duration>,
    /// Record message contents on tracing spans. Off by default (PII).
    #[serde(default)]
    pub trace_content: bool,
    /// Graph node currently executing; set by the graph executor.
    #[serde(default)]
    pub node: Option<String>,

    #[serde(skip)]
    callbacks: Vec<Arc<dyn CallbackHandler>>,
    #[serde(skip)]
    cancellation: CancellationToken,
    #[serde(skip)]
    sink: EventSink,
}

fn default_recursion_limit() -> u32 {
    DEFAULT_RECURSION_LIMIT
}

fn default_max_concurrency() -> usize {
    DEFAULT_MAX_CONCURRENCY
}

impl Default for RunConfig {
    fn default() -> Self {
        RunConfig {
            thread_id: None,
            checkpoint_id: None,
            run_id: Uuid::now_v7(),
            parent_run_id: None,
            run_name: None,
            tags: Vec::new(),
            metadata: Map::new(),
            configurable: Map::new(),
            recursion_limit: DEFAULT_RECURSION_LIMIT,
            max_concurrency: DEFAULT_MAX_CONCURRENCY,
            timeout: None,
            trace_content: false,
            node: None,
            callbacks: Vec::new(),
            cancellation: CancellationToken::new(),
            sink: EventSink::default(),
        }
    }
}

impl fmt::Debug for RunConfig {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.debug_struct("RunConfig")
            .field("thread_id", &self.thread_id)
            .field("checkpoint_id", &self.checkpoint_id)
            .field("run_id", &self.run_id)
            .field("parent_run_id", &self.parent_run_id)
            .field("run_name", &self.run_name)
            .field("tags", &self.tags)
            .field("metadata", &self.metadata)
            .field("configurable", &self.configurable)
            .field("recursion_limit", &self.recursion_limit)
            .field("max_concurrency", &self.max_concurrency)
            .field("timeout", &self.timeout)
            .field("node", &self.node)
            .field("callbacks", &self.callbacks.len())
            .field("cancelled", &self.cancellation.is_cancelled())
            .finish()
    }
}

impl RunConfig {
    /// A new config with a fresh `run_id` and default limits.
    pub fn new() -> Self {
        Self::default()
    }

    /// Set the thread id.
    pub fn thread_id(mut self, id: impl Into<String>) -> Self {
        self.thread_id = Some(id.into());
        self
    }

    /// Set the checkpoint to resume or fork from.
    pub fn checkpoint_id(mut self, id: impl Into<String>) -> Self {
        self.checkpoint_id = Some(id.into());
        self
    }

    /// Set the run name.
    pub fn run_name(mut self, name: impl Into<String>) -> Self {
        self.run_name = Some(name.into());
        self
    }

    /// Add a tag.
    pub fn tag(mut self, tag: impl Into<String>) -> Self {
        self.tags.push(tag.into());
        self
    }

    /// Add a metadata entry.
    pub fn metadata(mut self, key: impl Into<String>, value: Value) -> Self {
        self.metadata.insert(key.into(), value);
        self
    }

    /// Add a runtime option.
    pub fn configurable(mut self, key: impl Into<String>, value: Value) -> Self {
        self.configurable.insert(key.into(), value);
        self
    }

    /// Add a callback handler.
    pub fn callback(mut self, handler: impl CallbackHandler + 'static) -> Self {
        self.callbacks.push(Arc::new(handler));
        self
    }

    /// Add a shared callback handler.
    pub fn callback_arc(mut self, handler: Arc<dyn CallbackHandler>) -> Self {
        self.callbacks.push(handler);
        self
    }

    /// Set the max graph supersteps.
    pub fn recursion_limit(mut self, limit: u32) -> Self {
        self.recursion_limit = limit;
        self
    }

    /// Set the max concurrency (minimum 1).
    pub fn max_concurrency(mut self, n: usize) -> Self {
        self.max_concurrency = n.max(1);
        self
    }

    /// Set a timeout for the whole run.
    pub fn timeout(mut self, timeout: Duration) -> Self {
        self.timeout = Some(timeout);
        self
    }

    /// Record message contents on tracing spans.
    pub fn trace_content(mut self, on: bool) -> Self {
        self.trace_content = on;
        self
    }

    /// Use this cancellation token. Cancelling it stops the run with
    /// [`Error::Cancelled`](crate::Error::Cancelled).
    pub fn cancellation(mut self, token: CancellationToken) -> Self {
        self.cancellation = token;
        self
    }

    /// Set the current graph node (used by the graph executor).
    pub fn with_node(mut self, node: impl Into<String>) -> Self {
        self.node = Some(node.into());
        self
    }

    /// The cancellation token for this run.
    pub fn cancellation_token(&self) -> &CancellationToken {
        &self.cancellation
    }

    /// Whether the run was cancelled.
    pub fn is_cancelled(&self) -> bool {
        self.cancellation.is_cancelled()
    }

    /// Return [`Error::Cancelled`](crate::Error::Cancelled) if the run was cancelled.
    pub fn check_cancelled(&self) -> crate::Result<()> {
        if self.is_cancelled() {
            Err(crate::Error::Cancelled)
        } else {
            Ok(())
        }
    }

    /// Registered callback handlers.
    pub fn callbacks(&self) -> &[Arc<dyn CallbackHandler>] {
        &self.callbacks
    }

    /// A config for a nested run: same settings, new `run_id`, `parent_run_id` set.
    pub fn child(&self) -> Self {
        let mut c = self.clone();
        c.parent_run_id = Some(self.run_id);
        c.run_id = Uuid::now_v7();
        c
    }

    /// Whether anyone is listening for events (a stream or a callback).
    pub fn has_listeners(&self) -> bool {
        !self.sink.is_empty() || !self.callbacks.is_empty()
    }

    /// Send an event to active streams and callback handlers.
    pub async fn emit(&self, event: Event) {
        self.sink.send(&event);
        for cb in &self.callbacks {
            cb.on_event(&event, self).await;
        }
    }

    /// Report an error to callback handlers.
    pub async fn emit_error(&self, error: &crate::Error) {
        for cb in &self.callbacks {
            cb.on_error(error, self).await;
        }
    }

    /// Merge defaults from `other`: its tags and metadata are added, and its
    /// options apply where this config has none.
    pub fn merged_with(&self, other: &RunConfig) -> Self {
        let mut c = self.clone();
        for t in &other.tags {
            if !c.tags.contains(t) {
                c.tags.push(t.clone());
            }
        }
        for (k, v) in &other.metadata {
            c.metadata.entry(k.clone()).or_insert_with(|| v.clone());
        }
        for (k, v) in &other.configurable {
            c.configurable.entry(k.clone()).or_insert_with(|| v.clone());
        }
        c.callbacks.extend(other.callbacks.iter().cloned());
        if c.run_name.is_none() {
            c.run_name.clone_from(&other.run_name);
        }
        if c.timeout.is_none() {
            c.timeout = other.timeout;
        }
        c
    }

    pub(crate) fn with_sink_target(&self, tx: tokio::sync::mpsc::UnboundedSender<Event>) -> Self {
        let mut c = self.clone();
        c.sink = self.sink.with_target(tx);
        c
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use serde_json::json;

    #[test]
    fn serde_roundtrip_skips_handles() {
        let c = RunConfig::new()
            .thread_id("t")
            .tag("a")
            .metadata("k", json!(1));
        let v = serde_json::to_value(&c).unwrap();
        assert!(v.get("callbacks").is_none());
        let back: RunConfig = serde_json::from_value(v).unwrap();
        assert_eq!(back.thread_id.as_deref(), Some("t"));
        assert_eq!(back.run_id, c.run_id);
    }

    #[test]
    fn deserialize_minimal() {
        let c: RunConfig = serde_json::from_value(json!({})).unwrap();
        assert_eq!(c.recursion_limit, DEFAULT_RECURSION_LIMIT);
    }

    #[test]
    fn child_links_parent() {
        let c = RunConfig::new();
        let k = c.child();
        assert_eq!(k.parent_run_id, Some(c.run_id));
        assert_ne!(k.run_id, c.run_id);
    }

    #[test]
    fn cancellation() {
        let token = CancellationToken::new();
        let c = RunConfig::new().cancellation(token.clone());
        assert!(c.check_cancelled().is_ok());
        token.cancel();
        assert!(c.check_cancelled().is_err());
    }

    #[test]
    fn merge() {
        let a = RunConfig::new().tag("x").metadata("k", json!(1));
        let b = RunConfig::new()
            .tag("x")
            .tag("y")
            .metadata("k", json!(2))
            .run_name("n");
        let m = a.merged_with(&b);
        assert_eq!(m.tags, vec!["x", "y"]);
        assert_eq!(m.metadata["k"], 1);
        assert_eq!(m.run_name.as_deref(), Some("n"));
    }
}
